# Preflight: every sheet cell filled, every cross-sheet reference resolves, every ULTRAKILL member
# a sheet names exists in the decompiled game. Then generates src/Generated.cs from the rows.
# Usage: python -I tools/preflight.py <ultrakill-decomp-dir>   (exit 1 on any problem)
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DECOMP = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/ultrakill-decomp")
S = {n[:-5]: json.load(open(os.path.join(ROOT, "sheets", n), encoding="utf8"))
     for n in sorted(os.listdir(os.path.join(ROOT, "sheets"))) if n.endswith(".json")}
problems = []

for name, sh in S.items():
    cols = list(sh["columns"])
    for r in sh["rows"]:
        for c in cols:
            if c not in r or r[c] is None or r[c] == "":
                problems.append(f"{name}.{r.get('id')}.{c} is empty")
        for c in r:
            if c not in cols:
                problems.append(f"{name}.{r.get('id')}.{c} is not a declared column")
    ids = [r["id"] for r in sh["rows"]]
    if len(ids) != len(set(ids)):
        problems.append(f"{name} has duplicate ids")

for r in S["rarity_overrides"]["rows"]:
    if r["wikiRarity"] not in {x["value"] for x in S["rarities"]["rows"]}:
        problems.append(f"rarity_overrides.{r['id']}.wikiRarity unknown")
def ids(n): return {r["id"] for r in S[n]["rows"]}
for r in S["categories"]["rows"]:
    if r["defaultFireType"] not in ids("fire_types"):
        problems.append(f"categories.{r['id']}.defaultFireType -> {r['defaultFireType']} unresolved")
if [r["value"] for r in S["rarities"]["rows"]] != list(range(len(S["rarities"]["rows"]))):
    problems.append("rarities.value must be 0,1,2... in order (the menu indexes by it)")
if sorted(r["ukSlot"] for r in S["categories"]["rows"]) != [1, 2, 3, 4, 5, 6]:
    problems.append("categories.ukSlot must cover slots 1-6 once each")
for r in S["hooks"]["rows"]:
    if r["system"] not in ids("systems"):
        problems.append(f"hooks.{r['id']}.system -> {r['system']} unresolved")
for r in S["systems"]["rows"]:
    if r["id"] != "plugin" and not os.path.exists(os.path.join(ROOT, r["file"])):
        problems.append(f"systems.{r['id']}.file {r['file']} missing (unimplemented)")

def cs(cls):
    p = os.path.join(DECOMP, cls + ".cs")
    return open(p, encoding="utf8", errors="ignore").read() if os.path.exists(p) else ""
def has_member(cls, member):
    return re.search(r"\b" + re.escape(member) + r"\b", cs(cls)) is not None
gunsetter = cs("GunSetter")
for r in S["fire_types"]["rows"]:
    if r["ukSource"] != "none":
        if not re.search(r"public\s+\S+\s+" + re.escape(r["ukSource"]) + r"\s*;", gunsetter):
            problems.append(f"fire_types.{r['id']}.ukSource GunSetter.{r['ukSource']} not found")
        cls, fld = r["ukComponentField"].split(".")
        if not re.search(r"public GameObject " + fld + r"\s*;", cs(cls)):
            problems.append(f"fire_types.{r['id']}.ukComponentField {cls}.{fld} not found")
    flag = r["pg3dFlag"]
    if flag != "none" and flag not in open(os.path.join(ROOT, "tools", "extract_weapons.py")).read():
        problems.append(f"fire_types.{r['id']}.pg3dFlag {flag} is not read from PG3D")
for r in S["hooks"]["rows"]:
    for cls, mem in re.findall(r"\b([A-Z]\w+)\.(\w+)", r["target"]):
        if cs(cls) and not has_member(cls, mem):
            problems.append(f"hooks.{r['id']} {cls}.{mem} not in ULTRAKILL")
        if not cs(cls):
            problems.append(f"hooks.{r['id']} type {cls} not in ULTRAKILL")

# Data check against this PC's PG3D scan: every gun lands in a category and a fire type.
raw = os.path.join(ROOT, "work", "pg3d_weapons_raw.json")
if os.path.exists(raw):
    guns = json.load(open(raw))
    cat = {r["id"] for r in S["categories"]["rows"]}
    bad = [g["id"] for g in guns if g.get("categoryNabor") not in cat]
    if bad: problems.append(f"{len(bad)} PG3D guns have no category row: {bad[:10]}")
    print(f"data: {len(guns)} guns on this PC, {len(guns)-len(bad)} placed")
    rar = {r["value"] for r in S["rarities"]["rows"]}
    bad = [g["id"] for g in guns if g.get("rarity") not in rar]
    if bad: problems.append(f"{len(bad)} PG3D guns have no rarity row: {bad[:10]}")

if problems:
    print("PREFLIGHT FAILED"); [print(" -", p) for p in problems]; sys.exit(1)

# ---- codegen ----
def lit(v):
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, (int, float)): return (repr(float(v)) + "f") if isinstance(v, float) else str(v)
    return json.dumps(v)
out = ["// Generated by tools/preflight.py from sheets/*.json. Do not edit; change the sheet.",
       "namespace PixelGunArsenal {",
       "public struct Category { public int id, ukSlot, loadoutSize; public string name, defaultFireType, color; public float damageScale, reloadSeconds; }",
       "public struct FireType { public string id, pg3dFlag, ukSource, ukComponentField, damageFrom, shotsPerTrigger, autoFire; public int priority; public float spreadDegrees, range; }",
       "public struct Rarity { public int value; public string id, name, term, color; }",
       "public static class Sheets {"]
out.append(" public static readonly Category[] Categories = {")
for r in S["categories"]["rows"]:
    out.append("  new Category{" + ", ".join(f"{k}={lit(r[k])}" for k in S["categories"]["columns"]) + "},")
out.append(" };")
out.append(" public static readonly FireType[] FireTypes = {")
for r in sorted(S["fire_types"]["rows"], key=lambda r: r["priority"]):
    out.append("  new FireType{" + ", ".join(f"{k}={lit(r[k] if not isinstance(r[k], int) or k=='priority' else float(r[k]))}" for k in S["fire_types"]["columns"]) + "},")
out.append(" };")
out.append(" public static readonly Rarity[] Rarities = {")
for r in S["rarities"]["rows"]:
    out.append("  new Rarity{" + ", ".join(f"{k}={lit(r[k])}" for k in S["rarities"]["columns"]) + "},")
out.append(" };")
out.append(" public static readonly System.Collections.Generic.Dictionary<int, int> RarityOverrides = new System.Collections.Generic.Dictionary<int, int> {")
out.append(" " + ", ".join("{" + r["id"] + "," + str(r["wikiRarity"]) + "}" for r in S["rarity_overrides"]["rows"]))
out.append(" };")
for r in S["config"]["rows"]:
    out.append(f" public const string Cfg{r['id']}Default = {json.dumps(r['default'])}; // {r['what']}")
out.append("}}")
open(os.path.join(ROOT, "src", "Generated.cs"), "w", encoding="utf8").write("\n".join(out) + "\n")
print("PREFLIGHT CLEAN; wrote src/Generated.cs")
